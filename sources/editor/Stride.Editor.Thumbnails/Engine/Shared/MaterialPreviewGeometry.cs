using System;
using System.Collections.Generic;
using Stride.Core;
using Stride.Graphics.GeometricPrimitives;
using Stride.Rendering;
using Stride.Rendering.ProceduralModels;
using Buffer = Stride.Graphics.Buffer;

namespace Stride.Engine;

public enum EditorMaterialPrimitive { Sphere, Cube, Cylinder, Torus, Plane, Teapot, Cone, Capsule }

/// <summary>Primitive geometry shared with the reference material preview and thumbnail commands.</summary>
public static class MaterialPreviewGeometry
{
    public const string EffectName = "StrideEditorMaterialPreviewEffect";
    public static ProceduralModelDescriptor CreateDescriptor(EditorMaterialPrimitive primitive) => new()
    {
        Type = primitive switch
        {
            EditorMaterialPrimitive.Sphere => new SphereProceduralModel(),
            EditorMaterialPrimitive.Cube => new CubeProceduralModel(),
            EditorMaterialPrimitive.Cylinder => new CylinderProceduralModel(),
            EditorMaterialPrimitive.Torus => new TorusProceduralModel(),
            EditorMaterialPrimitive.Plane => new PlaneProceduralModel { GenerateBackFace = true, Normal = NormalDirection.UpZ },
            EditorMaterialPrimitive.Teapot => new TeapotProceduralModel(),
            EditorMaterialPrimitive.Cone => new ConeProceduralModel(),
            EditorMaterialPrimitive.Capsule => new CapsuleProceduralModel(),
            _ => throw new ArgumentOutOfRangeException(nameof(primitive)),
        },
    };
    public static Model CreatePreviewModel(IServiceRegistry services, Material material, EditorMaterialPrimitive primitive)
    {
        var model = CreateDescriptor(primitive).GenerateModel(services); model.Add(material); return model;
    }
    /// <summary>Populates the caller's real model while retaining every generated GPU buffer in its ownership scope.</summary>
    public static void PopulatePreviewModel(IServiceRegistry services, Material material, EditorMaterialPrimitive primitive,
        Model model, Action<Buffer> retainBuffer)
    {
        ArgumentNullException.ThrowIfNull(retainBuffer);
        var descriptor = CreateDescriptor(primitive);
        if (descriptor.Type is not PrimitiveProceduralModelBase generator)
            throw new InvalidOperationException("The registered material primitive has no native buffer generation scope.");
        generator.Generate(services, model, retainBuffer); model.Add(material);
    }
    public static Model CreateThumbnailModel(IServiceRegistry services, Material material)
        => new ProceduralModelDescriptor { Type = new SphereProceduralModel { MaterialInstance = { Material = material } } }.GenerateModel(services);
    public static Model CreateThumbnailModel(IServiceRegistry services, Material material, Action<Buffer> retainBuffer)
    {
        var model = new Model();
        new SphereProceduralModel { MaterialInstance = { Material = material } }.Generate(services, model, retainBuffer);
        return model;
    }

    /// <summary>Only for models generated by this helper; compiled model buffers belong to their content manager.</summary>
    public static void DisposeGeneratedModel(Model model)
    {
        var buffers = new HashSet<Buffer>();
        foreach (var mesh in model.Meshes)
        {
            foreach (var vertex in mesh.Draw.VertexBuffers) if (vertex.Buffer != null) buffers.Add(vertex.Buffer);
            if (mesh.Draw.IndexBuffer.Buffer != null) buffers.Add(mesh.Draw.IndexBuffer.Buffer);
        }
        foreach (var buffer in buffers) buffer.Dispose();
    }
}
