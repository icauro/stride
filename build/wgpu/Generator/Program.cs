using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using CppAst;

if (args.Length is < 2 or > 3)
    throw new ArgumentException("Usage: Generator <headers-directory> <output-directory> [--check]");
var headers = Path.GetFullPath(args[0]);
var output = Path.GetFullPath(args[1]);
var check = args.Length == 3 && args[2] == "--check";
if (args.Length == 3 && !check) throw new ArgumentException("Unknown option.");
using var manifest = JsonDocument.Parse(File.ReadAllText(Path.Combine(headers, "manifest.json")));
foreach (var entry in manifest.RootElement.GetProperty("headers").EnumerateObject())
{
    var bytes = File.ReadAllBytes(Path.Combine(headers, entry.Name));
    if (!Convert.ToHexStringLower(SHA256.HashData(bytes)).Equals(entry.Value.GetString(), StringComparison.Ordinal))
        throw new InvalidDataException($"Header hash mismatch: {entry.Name}");
}
var options = new CppParserOptions { ParseMacros = true, ParserKind = CppParserKind.C, TargetCpu = CppTargetCpu.X86_64 };
options.IncludeFolders.Add(headers);
var compilation = CppParser.ParseFile(Path.Combine(headers, "wgpu.h"), options);
foreach (var diagnostic in compilation.Diagnostics.Messages) Console.Error.WriteLine(diagnostic);
if (compilation.HasErrors) throw new InvalidDataException("Header parsing failed.");
var emitter = new Emitter(compilation, File.ReadAllText(Path.Combine(headers, "webgpu.h")) + "\n" + File.ReadAllText(Path.Combine(headers, "wgpu.h")), manifest.RootElement.GetProperty("release").GetString()!);
var generated = emitter.Generate();
var existing = Directory.Exists(output) ? Directory.GetFiles(output, "*.g.cs").Select(Path.GetFileName).ToHashSet(StringComparer.Ordinal) : [];
var legacyPath = Path.Combine(output, "WebGPU.g.cs");
var unexpected = existing.Except(generated.Keys, StringComparer.Ordinal).ToArray();
if (unexpected.Any(name => name != "WebGPU.g.cs") || (check && unexpected.Length != 0))
    throw new InvalidDataException("Unexpected generated files: " + string.Join(", ", unexpected));
if (!check && File.Exists(legacyPath) && !File.ReadAllText(legacyPath).StartsWith("// <auto-generated />\n// Generated from the hash-pinned wgpu-native ", StringComparison.Ordinal))
    throw new InvalidDataException("Legacy WebGPU.g.cs has an unexpected header; inspect it before replacing.");
if (!check) Directory.CreateDirectory(output);
foreach (var (name, contents) in generated)
{
    var path = Path.Combine(output, name);
    if (check)
    {
        if (!File.Exists(path) || File.ReadAllText(path) != contents)
            throw new InvalidDataException($"Generated bindings differ: {name}. Run the generator without --check.");
    }
    else File.WriteAllText(path, contents, new UTF8Encoding(false));
}
if (!check && File.Exists(legacyPath)) File.Delete(legacyPath);
Console.WriteLine($"{(check ? "Verified" : "Generated")} {emitter.StructCount} structs, {emitter.HandleCount} handles, {emitter.FunctionCount} functions.");

sealed class Emitter(CppCompilation api, string headerText, string release)
{
    private readonly StringBuilder code = new();
    private readonly Dictionary<string, string> files = new(StringComparer.Ordinal);
    private string? currentFile;
    private readonly HashSet<string> handles = api.Typedefs.Where(t => t.Name.StartsWith("WGPU", StringComparison.Ordinal) && t.ElementType is CppPointerType p && Unqualify(p.ElementType) is CppClass c && c.Name.EndsWith("Impl", StringComparison.Ordinal)).Select(t => t.Name).ToHashSet();
    private readonly HashSet<string> flags = Regex.Matches(headerText, @"typedef\s+WGPUFlags\s+(WGPU\w+)\s*;").Select(m => m.Groups[1].Value).ToHashSet();
    private readonly Dictionary<string, (string Type, string Body)> defaults = Regex.Matches(headerText.Replace("\\\r\n", "").Replace("\\\n", ""), @"#define[^\S\r\n]+(WGPU_\w+_INIT)[^\S\r\n]+_wgpu_MAKE_INIT_STRUCT\((WGPU\w+),[^\S\r\n]*\{([^\r\n]*)\}\)").ToDictionary(m => m.Groups[1].Value, m => (m.Groups[2].Value, m.Groups[3].Value));
    public int StructCount { get; private set; }
    public int HandleCount => handles.Count;
    public int FunctionCount { get; private set; }
    private void Line(string value = "") => code.Append(value).Append('\n');
    private static CppType Unqualify(CppType type) => type is CppQualifiedType q ? Unqualify(q.ElementType) : type;
    private static string Id(string name) => "@" + name;
    private static string Member(string type, string name)
    {
        var result = name.StartsWith(type + "_", StringComparison.Ordinal) ? name[(type.Length + 1)..] : name;
        return char.IsDigit(result[0]) ? "_" + result : Id(result);
    }
    private string Type(CppType type)
    {
        type = Unqualify(type);
        if (type is CppTypedef t)
        {
            if (handles.Contains(t.Name) || flags.Contains(t.Name)) return t.Name;
            var mapped = t.Name switch
            {
                "uint8_t" => "byte", "uint16_t" => "ushort", "uint32_t" => "uint", "uint64_t" => "ulong",
                "int8_t" => "sbyte", "int16_t" => "short", "int32_t" => "int", "int64_t" => "long",
                "size_t" or "uintptr_t" => "nuint", "intptr_t" => "nint", "WGPUBool" => "uint", "WGPUFlags" or "WGPUSubmissionIndex" => "ulong", _ => null
            };
            return mapped ?? Type(t.ElementType);
        }
        if (type is CppPrimitiveType primitive) return primitive.Kind switch
        {
            CppPrimitiveKind.Void => "void", CppPrimitiveKind.Char or CppPrimitiveKind.UnsignedChar => "byte",
            CppPrimitiveKind.Short => "short", CppPrimitiveKind.UnsignedShort => "ushort",
            CppPrimitiveKind.Int => "int", CppPrimitiveKind.UnsignedInt => "uint", CppPrimitiveKind.LongLong => "long",
            CppPrimitiveKind.UnsignedLongLong => "ulong", CppPrimitiveKind.Float => "float", CppPrimitiveKind.Double => "double",
            _ => throw new NotSupportedException($"Unsupported primitive: {type}")
        };
        if (type is CppEnum e) return e.Name;
        if (type is CppClass c && c.Name.StartsWith("WGPU", StringComparison.Ordinal) && !c.IsAnonymous) return c.Name;
        if (type is CppPointerType p)
        {
            if (Unqualify(p.ElementType) is CppFunctionType f) return FunctionPointer(f);
            return Type(p.ElementType) + "*";
        }
        throw new NotSupportedException($"Unsupported C type: {type.GetDisplayName()} ({type.GetType().Name})");
    }
    private string FunctionPointer(CppFunctionType function) => "delegate* unmanaged[Cdecl]<" + string.Join(", ", function.Parameters.Select(p => Type(p.Type)).Append(Type(function.ReturnType))) + ">";
    private void StartFile(string name)
    {
        if (currentFile is not null) files.Add(currentFile, code.ToString().TrimEnd() + "\n");
        code.Clear();
        currentFile = name;
        Line("// <auto-generated />");
        Line($"// Generated from the hash-pinned wgpu-native {release} headers. Do not edit.");
        Line("#nullable enable");
        Line("using System;");
        Line("using System.Runtime.CompilerServices;");
        Line("using System.Runtime.InteropServices;");
        Line("namespace Stride.Graphics.WebGPU;");
        Line();
    }
    public IReadOnlyDictionary<string, string> Generate()
    {
        var initializerCount = Regex.Matches(headerText, @"(?m)^#define\s+WGPU_\w+_INIT\b").Count;
        if (defaults.Count != initializerCount) throw new NotSupportedException($"Only {defaults.Count}/{initializerCount} native initializer macros were recognized.");
        StartFile("Enums.g.cs");
        foreach (var enumeration in api.Enums.Where(e => e.Name.StartsWith("WGPU", StringComparison.Ordinal)).OrderBy(e => e.Name, StringComparer.Ordinal))
        {
            Line($"public enum {enumeration.Name} : uint"); Line("{");
            foreach (var item in enumeration.Items)
                Line($"    {Member(enumeration.Name, item.Name)} = unchecked((uint){item.Value}L),");
            Line("}"); Line();
        }
        StartFile("Flags.g.cs");
        foreach (var flag in flags.Order(StringComparer.Ordinal))
        {
            Line("[Flags]"); Line($"public enum {flag} : ulong"); Line("{");
            var values = Regex.Matches(headerText, @"static\s+const\s+" + flag + @"\s+(\w+)\s*=\s*([^;]+);");
            if (values.Count == 0 || values.Count != Regex.Matches(headerText, @"static\s+const\s+" + flag + @"\s+\w+\s*=").Count)
                throw new NotSupportedException($"Unsupported flag constant expression in {flag}.");
            foreach (Match value in values)
            {
                var expression = value.Groups[2].Value.Trim();
                if (!Regex.IsMatch(expression, @"^(?:0x[0-9a-fA-F]+|[0-9]+|\s|<<|\||[()])+$"))
                    throw new NotSupportedException($"Unsupported flag value: {expression}");
                expression = Regex.Replace(expression, @"\b(0x[0-9a-fA-F]+|[0-9]+)(?=\s*<<)", "$1UL");
                Line($"    {Member(flag, value.Groups[1].Value)} = {expression},");
            }
            Line("}"); Line();
        }
        StartFile("Handles.g.cs");
        foreach (var handle in handles.Order(StringComparer.Ordinal))
        {
            Line("[StructLayout(LayoutKind.Sequential)]");
            Line($"public readonly struct {handle}(nint handle) : IEquatable<{handle}>"); Line("{");
            Line("    public readonly nint Handle = handle;");
            Line($"    public bool Equals({handle} other) => Handle == other.Handle;");
            Line($"    public override bool Equals(object? obj) => obj is {handle} other && Equals(other);");
            Line("    public override int GetHashCode() => Handle.GetHashCode();");
            Line($"    public static bool operator ==({handle} left, {handle} right) => left.Equals(right);");
            Line($"    public static bool operator !=({handle} left, {handle} right) => !left.Equals(right);");
            Line("}"); Line();
        }
        StartFile("Structs.g.cs");
        foreach (var structure in api.Classes.Where(c => c.Name.StartsWith("WGPU", StringComparison.Ordinal) && c.SizeOf > 0 && !c.Name.EndsWith("Impl", StringComparison.Ordinal)).OrderBy(c => c.Name, StringComparer.Ordinal))
        {
            if (structure.IsAnonymous || structure.ClassKind == CppClassKind.Union) throw new NotSupportedException($"Unsupported aggregate: {structure.Name}");
            Line("[StructLayout(LayoutKind.Sequential)]");
            Line($"public unsafe struct {structure.Name}"); Line("{");
            foreach (var field in structure.Fields)
            {
                if (field.Type is CppArrayType) throw new NotSupportedException($"Inline array requires explicit handling: {structure.Name}.{field.Name}");
                if (field.Type is CppClass { IsAnonymous: true, ClassKind: CppClassKind.Union } union)
                {
                    Line($"    public {field.Name}__Union {Id(field.Name)};");
                    Line("    [StructLayout(LayoutKind.Explicit)]");
                    Line($"    public struct {field.Name}__Union"); Line("    {");
                    foreach (var member in union.Fields)
                        Line($"        [FieldOffset(0)] public {Type(member.Type)} {Id(member.Name)};");
                    Line("    }");
                    continue;
                }
                try { Line($"    public {Type(field.Type)} {Id(field.Name)};"); }
                catch (NotSupportedException e) { throw new NotSupportedException($"{structure.Name}.{field.Name}: {e.Message}", e); }
            }
            var initializer = defaults.Values.SingleOrDefault(d => d.Type == structure.Name);
            if (initializer.Type is not null)
                Line($"    public static {structure.Name} CreateDefault() => {Initializer(initializer.Type, initializer.Body)};");
            Line("}"); Line(); StructCount++;
        }
        StartFile("Constants.g.cs");
        Line("public static unsafe partial class WebGPU"); Line("{");
        Line("    internal const string LibraryName = \"wgpu_native\";");
        var version = release.TrimStart('v').Split('.').Select(byte.Parse).ToArray();
        if (version.Length != 4) throw new InvalidDataException("Expected four-part wgpu-native version.");
        var packedVersion = ((uint)version[0] << 24) | ((uint)version[1] << 16) | ((uint)version[2] << 8) | version[3];
        Line($"    public const string NativeRelease = \"{release}\";");
        Line($"    public const uint NativeVersion = 0x{packedVersion:x8};");
        foreach (var macro in api.Macros.Where(m => m.Name.StartsWith("WGPU_", StringComparison.Ordinal) && !m.Name.EndsWith("_INIT", StringComparison.Ordinal) && !string.IsNullOrWhiteSpace(m.Value)))
        {
            var constant = macro.Name switch
            {
                "WGPU_TRUE" => "const uint WGPU_TRUE = 1", "WGPU_FALSE" => "const uint WGPU_FALSE = 0",
                "WGPU_STRLEN" or "WGPU_WHOLE_MAP_SIZE" => $"static readonly nuint {macro.Name} = nuint.MaxValue",
                "WGPU_WHOLE_SIZE" or "WGPU_LIMIT_U64_UNDEFINED" => $"const ulong {macro.Name} = ulong.MaxValue",
                "WGPU_ARRAY_LAYER_COUNT_UNDEFINED" or "WGPU_COPY_STRIDE_UNDEFINED" or "WGPU_DEPTH_SLICE_UNDEFINED" or "WGPU_LIMIT_U32_UNDEFINED" or "WGPU_MIP_LEVEL_COUNT_UNDEFINED" or "WGPU_QUERY_SET_INDEX_UNDEFINED" => $"const uint {macro.Name} = uint.MaxValue",
                "WGPU_DEPTH_CLEAR_VALUE_UNDEFINED" => "const float WGPU_DEPTH_CLEAR_VALUE_UNDEFINED = float.NaN",
                "WGPU_EXPORT" => null,
                _ => throw new NotSupportedException($"Unsupported constant macro: {macro.Name} = {macro.Value}")
            };
            if (constant is not null) Line("    public " + constant + ";");
        }
        Line("}");
        StartFile("Functions.g.cs");
        Line("public static unsafe partial class WebGPU"); Line("{");
        foreach (var function in api.Functions.Where(f => f.Name.StartsWith("wgpu", StringComparison.Ordinal)).OrderBy(f => f.Name, StringComparer.Ordinal))
        {
            Line($"    [LibraryImport(LibraryName, EntryPoint = \"{function.Name}\")]");
            Line("    [UnmanagedCallConv(CallConvs = [typeof(CallConvCdecl)])]");
            Line($"    public static partial {Type(function.ReturnType)} {function.Name}({string.Join(", ", function.Parameters.Select((p, i) => Type(p.Type) + " " + Id(string.IsNullOrEmpty(p.Name) ? "arg" + i : p.Name)))});");
            FunctionCount++;
        }
        Line("}");
        files.Add(currentFile!, code.ToString().TrimEnd() + "\n");
        return files;
    }
    private string Initializer(string type, string body)
    {
        var parts = new List<string>();
        var depth = 0; var start = 0;
        for (var i = 0; i < body.Length; i++)
        {
            if (body[i] is '(' or '{') depth++;
            if (body[i] is ')' or '}') depth--;
            if (depth == 0 && body.AsSpan(i).StartsWith("_wgpu_COMMA"))
            { parts.Add(body[start..i]); i += "_wgpu_COMMA".Length - 1; start = i + 1; }
        }
        if (!string.IsNullOrWhiteSpace(body[start..])) parts.Add(body[start..]);
        var assignments = new List<string>();
        foreach (var part in parts)
        {
            var match = Regex.Match(part.Trim(), @"^/\*\.(\w+)=\*/(.*)$", RegexOptions.Singleline);
            if (!match.Success) throw new NotSupportedException($"Unsupported default initializer in {type}: {part}");
            var expression = match.Groups[2].Value.Trim();
            var cast = Regex.Match(expression, @"^\((WGPU\w+)\)(.*)$");
            if (cast.Success) expression = cast.Groups[2].Value.Trim();
            string value;
            if (expression is "NULL" or "_wgpu_STRUCT_ZERO_INIT" || expression.StartsWith("_wgpu_ENUM_ZERO_INIT(", StringComparison.Ordinal)) value = "default";
            else if (defaults.TryGetValue(expression, out var nested)) value = nested.Type + ".CreateDefault()";
            else if (expression.StartsWith("_wgpu_MAKE_INIT_STRUCT(", StringComparison.Ordinal))
            {
                var firstComma = expression.IndexOf(',');
                var nestedType = expression["_wgpu_MAKE_INIT_STRUCT(".Length..firstComma].Trim();
                value = Initializer(nestedType, expression[(expression.IndexOf('{') + 1)..expression.LastIndexOf('}')]);
            }
            else if (expression.StartsWith("WGPU_", StringComparison.Ordinal)) value = "WebGPU." + expression;
            else if (expression.StartsWith("WGPU", StringComparison.Ordinal))
            {
                var owner = api.Enums.FirstOrDefault(e => e.Items.Any(i => i.Name == expression));
                if (owner is not null) value = owner.Name + "." + Member(owner.Name, expression);
                else
                {
                    var split = expression.IndexOf('_');
                    if (split < 0) throw new NotSupportedException(expression);
                    value = expression[..split] + "." + Member(expression[..split], expression);
                }
            }
            else if (Regex.IsMatch(expression, @"^(0x[0-9A-Fa-f]+|[0-9]+(\.[0-9]*)?f?)$"))
                value = Regex.Replace(expression, @"\.(f?)$", ".0$1");
            else throw new NotSupportedException($"Unsupported default value: {expression}");
            if (cast.Success) value = "(" + cast.Groups[1].Value + ")" + value;
            assignments.Add(Id(match.Groups[1].Value) + " = " + value);
        }
        return "new " + type + " { " + string.Join(", ", assignments) + " }";
    }
}
